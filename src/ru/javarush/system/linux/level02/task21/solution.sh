# Запуск трёх фоновых процессов
sleep 200 &  # Процесс 1
sleep 300 &  # Процесс 2
sleep 400 &  # Процесс 3

# Пауза, чтобы процессы успели запуститься
sleep 1

# Вывод списка текущих процессов для поиска PID
echo "Список текущих процессов:"
ps

# Получение PID одного из процессов `sleep`
pid_to_kill=$(ps -o pid,cmd | grep sleep | head -n 1 | awk '{print $1}')

# Завершение процесса с указанным PID
echo "Завершение процесса с PID: $pid_to_kill"
kill $pid_to_kill

# Проверка завершения процесса
echo "Список процессов после завершения одного из них:"
ps