#!/bin/bash

# Вывод информации обо всех сетевых интерфейсах системы
ip addr

# Определение основного сетевого интерфейса по маршруту по умолчанию
MAIN_IFACE="enp6s0"

# Если основной интерфейс не найден или сеть отключена — выводим сообщение
if [ -z "$MAIN_IFACE" ]; then
  echo "Основной сетевой интерфейс не найден или сеть отключена."
  exit 0
fi

# Получение IPv4-адреса основного интерфейса
IPV4=$(ip -4 addr show "$MAIN_IFACE" | grep -oP '(?<=inet\s)\d+(\.\d+){3}')

# Вывод IPv4-адреса основного интерфейса или сообщения об ошибке
if [ -n "$IPV4" ]; then
  echo "$IPV4"
else
  echo "Основной сетевой интерфейс не найден или сеть отключена."
fi
