#!/bin/bash

# Определение подключённых устройств с использованием команды lsblk
# Вывод устройств для пользователя
echo "Список подключённых устройств:"
lsblk

# Пользователь должен указать раздел для форматирования в FAT32
echo "Введите имя раздела для форматирования в FAT32 (например, /dev/sdc1):"
read FAT32_PARTITION

# Форматирование выбранного раздела в файловую систему FAT32
# mkfs.vfat выполняет создание файловой системы FAT32
echo "Форматирование раздела $FAT32_PARTITION в файловую систему FAT32..."
sudo mkfs.vfat $FAT32_PARTITION

# Проверка результата с использованием команды blkid
echo "Результат форматирования в FAT32:"
blkid | grep $FAT32_PARTITION

# Пользователь должен указать другой раздел для форматирования в XFS
echo "Введите имя раздела для форматирования в XFS (например, /dev/sdd1):"
read XFS_PARTITION

# Форматирование выбранного раздела в файловую систему XFS
# mkfs.xfs выполняет создание файловой системы XFS
echo "Форматирование раздела $XFS_PARTITION в файловую систему XFS..."
sudo mkfs.xfs $XFS_PARTITION

# Подтверждение изменений с использованием команды blkid
echo "Результат форматирования в XFS:"
blkid | grep $XFS_PARTITION